import {
  installServiceId,
  REMOVAL_SERVICE,
  type BaseboardAction,
  type CurrentFloor,
  type MoistureMethod,
  type NewFloor,
  type Pattern,
  type Subfloor,
} from "./catalog";
import type { WorkLine } from "./materials";

/** Pattern 2: a complete form per area. */
export type Rect = { id: string; length: number | null; width: number | null };

export type Area = {
  id: string;
  name: string;
  /** "rects": length × width (one or more rectangles); "total": sq ft typed directly. */
  measureMode: "rects" | "total";
  rects: Rect[];
  totalSqFt: number | null;
  currentFloor: CurrentFloor | null;
  removeCurrent: boolean;
  newFloor: NewFloor | null;
  pattern: Pattern;
  subfloor: Subfloor | null;
  leveling: boolean;
  levelingSqFt: number | null;
  baseboard: BaseboardAction;
  baseboardLf: number | null;
  quarterRoundLf: number | null;
  transitions: number;
  stairs: number;
  moistureMethod: MoistureMethod | null;
  moistureReading: number | null;
  /** Object URLs of the photos taken on the phone (prototype: they never leave the device). */
  photos: string[];
  notes: string;
};

export function emptyArea(id: string, name: string): Area {
  return {
    id,
    name,
    measureMode: "rects",
    rects: [{ id: `${id}-r1`, length: null, width: null }],
    totalSqFt: null,
    currentFloor: null,
    removeCurrent: true,
    newFloor: null,
    pattern: "straight",
    subfloor: null,
    leveling: false,
    levelingSqFt: null,
    baseboard: "keep",
    baseboardLf: null,
    quarterRoundLf: null,
    transitions: 0,
    stairs: 0,
    moistureMethod: null,
    moistureReading: null,
    photos: [],
    notes: "",
  };
}

export function areaSqFt(area: Area): number {
  if (area.measureMode === "total") return area.totalSqFt ?? 0;
  return area.rects.reduce((sum, r) => sum + (r.length ?? 0) * (r.width ?? 0), 0);
}

/** Perimeter suggestion when the area is a single rectangle. */
export function suggestedPerimeter(area: Area): number | null {
  if (area.measureMode !== "rects" || area.rects.length !== 1) return null;
  const [rect] = area.rects;
  if (!rect?.length || !rect.width) return null;
  return 2 * (rect.length + rect.width);
}

export function missingFields(area: Area): string[] {
  const missing: string[] = [];
  if (areaSqFt(area) <= 0) missing.push("medidas");
  if (!area.currentFloor) missing.push("piso atual");
  if (!area.newFloor) missing.push("piso novo");
  if (!area.subfloor) missing.push("contrapiso");
  return missing;
}

/** Work lines generated by an area: the same lines pattern 1 asks for by hand. */
export function deriveLines(area: Area): WorkLine[] {
  const sqft = areaSqFt(area);
  const lines: WorkLine[] = [];
  const push = (serviceId: string, quantity: number | null) => {
    if (quantity && quantity > 0) lines.push({ serviceId, quantity, area: area.name });
  };

  const removal = area.currentFloor ? REMOVAL_SERVICE[area.currentFloor] : null;
  if (removal && area.removeCurrent) push(removal, sqft);
  if (area.leveling) push("pr-level", area.levelingSqFt ?? sqft);
  if (area.newFloor) push(installServiceId(area.newFloor, area.pattern), sqft);
  if (area.baseboard === "replace") push("rm-baseboard", area.baseboardLf);
  if (area.baseboard !== "keep") push("fn-baseboard", area.baseboardLf);
  push("fn-quarter", area.quarterRoundLf);
  push("fn-transition", area.transitions);
  if (area.stairs > 0) {
    push("fn-stairs", area.stairs);
    push("fn-stairnose", area.stairs);
  }
  return lines;
}

